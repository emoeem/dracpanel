// Collect the licenses of the production dependencies that end up in dist/.
//
// Runs at the end of `pnpm build` (after `vite build`, because Vite empties the
// output directory). Only the direct `dependencies` of package.json are listed:
// devDependencies never reach the shipped UI, and transitive packages are
// covered by the license files their own publisher ships.
//
// Node built-ins only — no dependencies, so the script cannot rot behind the
// lockfile.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const OUT_DIR = join(ROOT, "dist", "licenses");
const OUT_FILE = join(OUT_DIR, "THIRD-PARTY.md");

/** npm allows `license` as a string, or (older) an object / array of objects. */
function spdx(manifest) {
  const value = manifest.license ?? manifest.licenses;
  if (typeof value === "string" && value.trim() !== "") {
    return value.trim();
  }
  if (Array.isArray(value)) {
    const types = value.map((entry) => (typeof entry === "string" ? entry : entry?.type)).filter(Boolean);
    return types.length > 0 ? types.join(" OR ") : "UNKNOWN";
  }
  if (typeof value === "object" && value !== null && typeof value.type === "string") {
    return value.type.trim() === "" ? "UNKNOWN" : value.type.trim();
  }
  return "UNKNOWN";
}

async function readJson(path) {
  return JSON.parse(await readFile(path, "utf8"));
}

async function main() {
  const root = await readJson(join(ROOT, "package.json"));
  const names = Object.keys(root.dependencies ?? {}).sort();

  const rows = [];
  const missing = [];

  for (const name of names) {
    let manifest;
    try {
      manifest = await readJson(join(ROOT, "node_modules", name, "package.json"));
    } catch {
      // Not installed (e.g. a build without node_modules): keep the entry so the
      // list never silently shrinks.
      missing.push(name);
      rows.push({ name, version: "?", license: "UNKNOWN" });
      continue;
    }
    rows.push({
      name: manifest.name ?? name,
      version: manifest.version ?? "?",
      license: spdx(manifest),
    });
  }

  const unknown = rows.filter((row) => row.license === "UNKNOWN").map((row) => row.name);

  const lines = [
    "# Third-party licenses",
    "",
    `Generated by \`scripts/gen-licenses.mjs\` at the end of \`pnpm build\` for DracPanel ${root.version ?? ""}. Do not edit by hand.`,
    "",
    "This file lists the **production** dependencies of `package.json` whose code is bundled into `dist/`.",
    "Dev dependencies are build-time only and are not shipped. Transitive packages are covered by the",
    "license files their own publishers ship.",
    "",
    `DracPanel itself is licensed under **${root.license ?? "GPL-3.0-or-later"}** (see [LICENSE](../../LICENSE));`,
    "non-npm assets (fonts, icons, GeoIP data) are credited in [NOTICE](../../NOTICE).",
    "",
    "| Package | Version | License (SPDX) |",
    "| --- | --- | --- |",
    ...rows.map((row) => `| \`${row.name}\` | ${row.version} | ${row.license} |`),
    "",
    "`UNKNOWN` means the package declares no license field — check its own LICENSE file before redistributing.",
    "",
  ];

  await mkdir(OUT_DIR, { recursive: true });
  await writeFile(OUT_FILE, `${lines.join("\n")}\n`, "utf8");

  console.log(`[licenses] wrote ${rows.length} entries to dist/licenses/THIRD-PARTY.md`);
  if (unknown.length > 0) {
    console.warn(`[licenses] missing license field: ${unknown.join(", ")}`);
  }
  if (missing.length > 0) {
    console.warn(`[licenses] not found in node_modules: ${missing.join(", ")}`);
  }
}

main().catch((error) => {
  console.error("[licenses] failed:", error instanceof Error ? error.message : error);
  process.exit(1);
});
