const KEYWORDS: readonly { word: string; code: string }[] = Object.entries(NAME_TO_CODE).map(
  ([word, code]) => ({ word, code }),
);

/** Normalize a GeoIP country field (name or code) into an ISO alpha-2 code. */
export function countryCodeOf(value: string | null | undefined): string | null {
  if (value === null || value === undefined) {
    return null;
  }
  const trimmed = value.trim();
  if (/^[a-zA-Z]{2}$/.test(trimmed)) {
    return trimmed.toUpperCase();
  }
  return NAME_TO_CODE[trimmed.toLowerCase()] ?? null;
}

/** Regional-indicator flag for a two-letter code (no external asset needed). */
export function flagEmoji(code: string): string {
  const upper = code.trim().toUpperCase();
  if (!/^[A-Z]{2}$/.test(upper)) {
    return "";
  }
  return String.fromCodePoint(
    ...upper.split("").map((letter) => 0x1f1e6 + letter.charCodeAt(0) - 65),
  );
}

const EXISTING_FLAG = /[\u{1F1E6}-\u{1F1FF}]{2}/u;

/** Find a flag in a node name: an existing emoji first, then a country word. */
export function flagOfText(value: string): string {
  const existing = value.match(EXISTING_FLAG);
  if (existing) {
    return existing[0];
  }
  const lower = value.toLowerCase();
  for (const { word, code } of KEYWORDS) {
    if (lower.includes(word)) {
      return flagEmoji(code);
    }
  }
  return "";
}
