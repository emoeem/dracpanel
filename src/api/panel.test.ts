import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";

import { loadServersState, saveServersState } from "./config";
import {
  extractApiService,
  GeoIpUnavailableError,
  getGeoIp,
  lockPanel,
  MANAGED_SERVER_ID,
  normalizeConfigJson,
  PANEL_TOKEN_KEY,
  probePanelEndpoint,
  setSubscriptionSchedule,
} from "./panel";
import { loadStoredJson, saveStoredJson } from "../lib/storage";

const API_CONFIG = {
  services: [
    { type: "api", listen: "127.0.0.1", listen_port: 9091, secret: "s3cret" },
    { type: "clash_api", listen_port: 9090 },
  ],
};

class MemoryStorage {
  private map = new Map<string, string>();

  getItem(key: string): string | null {
    return this.map.get(key) ?? null;
  }

  setItem(key: string, value: string) {
    this.map.set(key, String(value));
  }

  removeItem(key: string) {
    this.map.delete(key);
  }
}

beforeEach(() => {
  vi.stubGlobal("localStorage", new MemoryStorage());
});

afterEach(() => {
  vi.unstubAllGlobals();
});

describe("normalizeConfigJson", () => {
  it("strips line and block comments and trailing commas", () => {
    const text = `{
      // line comment, with } and ,
      "log": { "level": "warn" }, /* block comment */
      "services": [
        { "type": "api", "listen_port": 9091, "secret": "s3cret" },
      ],
    }`;
    expect(JSON.parse(normalizeConfigJson(text))).toEqual({
      log: { level: "warn" },
      services: [{ type: "api", listen_port: 9091, secret: "s3cret" }],
    });
  });

  it("does not treat comment markers inside strings as comments", () => {
    const text = `{"secret": "a//b/*c*/", "path": "http://example.com"}`;
    expect(JSON.parse(normalizeConfigJson(text))).toEqual({
      secret: "a//b/*c*/",
      path: "http://example.com",
    });
  });

  it("keeps escaped quotes intact", () => {
    const text = String.raw`{"name": "a\"//b", "secret": "x"}`;
    expect(JSON.parse(normalizeConfigJson(text))).toEqual({ name: 'a"//b', secret: "x" });
  });
});

describe("extractApiService", () => {
  it("reads listen_port and secret from services.api", () => {
    expect(extractApiService(JSON.stringify(API_CONFIG))).toEqual({ port: 9091, secret: "s3cret" });
  });

  it("accepts a config with comments and trailing commas", () => {
    const text = `{
      // generated by hand
      "services": [
        {
          "type": "api",
          "listen": "127.0.0.1",
          "listen_port": 9091,
          "secret": "s3cret",
        },
      ],
    }`;
    expect(extractApiService(text)).toEqual({ port: 9091, secret: "s3cret" });
  });

  it("returns an empty secret instead of inventing one", () => {
    expect(
      extractApiService(
        JSON.stringify({ services: [{ type: "api", listen_port: 9091 }] }),
      ),
    ).toEqual({ port: 9091, secret: "" });
  });

  it("returns null when there is no api service", () => {
    expect(extractApiService(JSON.stringify({ services: [{ type: "clash_api" }] }))).toBeNull();
    expect(extractApiService(JSON.stringify({ log: {} }))).toBeNull();
  });

  it("rejects a missing or invalid listen_port instead of falling back to 9091", () => {
    expect(() =>
      extractApiService(JSON.stringify({ services: [{ type: "api", secret: "s" }] })),
    ).toThrow(/listen_port/);
    expect(() =>
      extractApiService(
        JSON.stringify({ services: [{ type: "api", listen_port: "9091", secret: "s" }] }),
      ),
    ).toThrow(/listen_port/);
    expect(() =>
      extractApiService(JSON.stringify({ services: [{ type: "api", listen_port: 70000 }] })),
    ).toThrow(/listen_port/);
  });

  it("distinguishes an invalid config from a config without services.api", () => {
    expect(() => extractApiService("{not json")).toThrow(/Failed to parse/);
    expect(() => extractApiService("[]")).toThrow(/JSON object/);
  });
});

describe("lockPanel", () => {
  it("clears the token and cache and removes only the managed server", () => {
    localStorage.setItem(PANEL_TOKEN_KEY, "token");
    saveStoredJson("panel-api-cache", { mtime: 1, bytes: 2, port: 9091, secret: "s" });
    saveServersState({
      servers: [
        { id: MANAGED_SERVER_ID, name: "local", url: "127.0.0.1:9091", secret: "s" },
        { id: "remote", name: "remote", url: "10.0.0.1:9090", secret: "r" },
      ],
      activeId: MANAGED_SERVER_ID,
    });

    lockPanel();

    expect(localStorage.getItem(PANEL_TOKEN_KEY)).toBeNull();
    expect(loadStoredJson("panel-api-cache")).toBeNull();
    expect(loadServersState()).toEqual({
      servers: [{ id: "remote", name: "remote", url: "10.0.0.1:9090", secret: "r" }],
      activeId: "remote",
    });
  });
});

describe("setSubscriptionSchedule", () => {
  it("posts the interval with the panel token", async () => {
    localStorage.setItem(PANEL_TOKEN_KEY, "token");
    const calls: { url: string; init?: RequestInit }[] = [];
    vi.stubGlobal(
      "fetch",
      vi.fn(async (input: string, init?: RequestInit) => {
        calls.push({ url: input, init });
        return new Response(JSON.stringify({ ok: true, message: "saved" }), {
          status: 200,
          headers: { "Content-Type": "application/json" },
        });
      }),
    );

    await expect(setSubscriptionSchedule("abc12345", 3600)).resolves.toEqual({
      ok: true,
      message: "saved",
    });
    expect(calls[0]?.url).toBe("/api/subscriptions/abc12345/schedule");
    expect(calls[0]?.init?.method).toBe("POST");
    expect(calls[0]?.init?.body).toBe('{"update_interval":3600}');
    expect(calls[0]?.init?.headers).toBeInstanceOf(Headers);
    expect((calls[0]?.init?.headers as Headers).get("X-Panel-Token")).toBe("token");
  });
});

describe("probePanelEndpoint", () => {
  it("distinguishes an absent route from a known route's 404", async () => {
    // Probes only run with a panel configured; the client fails fast without one.
    localStorage.setItem(PANEL_TOKEN_KEY, "token");
    const responses = [
      new Response(JSON.stringify({ ok: false, message: "未知接口：GET /api/geoip" }), {
        status: 404,
        headers: { "Content-Type": "application/json" },
      }),
      new Response(JSON.stringify({ ok: false, message: "找不到备份" }), {
        status: 404,
        headers: { "Content-Type": "application/json" },
      }),
      new Response(JSON.stringify({ ok: true }), {
        status: 200,
        headers: { "Content-Type": "application/json" },
      }),
    ];
    vi.stubGlobal(
      "fetch",
      vi.fn(async () => responses.shift()!),
    );

    await expect(probePanelEndpoint("/geoip?ip=1.1.1.1")).resolves.toMatchObject({
      supported: false,
      status: 404,
    });
    await expect(probePanelEndpoint("/config/backups/missing.json")).resolves.toMatchObject({
      supported: true,
      status: 404,
    });
    await expect(probePanelEndpoint("/logs?n=1")).resolves.toMatchObject({
      supported: true,
    });
  });
});

describe("getGeoIp", () => {
  it("maps 404 to null and 503 to GeoIpUnavailableError", async () => {
    localStorage.setItem(PANEL_TOKEN_KEY, "token");
    const responses = [
      new Response(JSON.stringify({ ok: false, message: "private or unresolvable ip" }), {
        status: 404,
        headers: { "Content-Type": "application/json" },
      }),
      new Response(JSON.stringify({ ok: false, message: "geoip database unavailable" }), {
        status: 503,
        headers: { "Content-Type": "application/json" },
      }),
    ];
    vi.stubGlobal(
      "fetch",
      vi.fn(async () => responses.shift()!),
    );

    await expect(getGeoIp("10.0.0.1")).resolves.toBeNull();
    await expect(getGeoIp("1.1.1.1")).rejects.toBeInstanceOf(GeoIpUnavailableError);
  });
});
